{
    const Tr *t = ui_lang == 2 ? F : T;
    size_t i, n = ui_lang == 2 ? sizeof(F) / sizeof(F[0]) : sizeof(T) / sizeof(T[0]);
    if (!ui_lang || !s || !s[0]) return s;
    for (i = 0; i < n; i++)
        if (t[i].en[0] == s[0] && !strcmp(t[i].en, s)) return t[i].es;
    return s;
}
